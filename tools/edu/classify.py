EXTRA = set(json.load(open("../bank/sets.json"))["extra"]["excel"])
tier = {}
for t, s in TIERS.items():
    for n in s.split():
        assert n in names, f"unknown {n}"
        assert n not in tier, f"twice {n}"
        tier[n] = t

core = {}
for t, s in CORE_TIERS.items():
    for n in s.split():
        assert n in names and n not in EXTRA, f"not a default-set function: {n}"
        assert n not in core, f"twice {n}"
        core[n] = t
missing = names - EXTRA - set(core)
assert not missing, f"default-set functions without a league: {sorted(missing)}"
tier.update(core)

# The seven skills (leagues 5-1): by Microsoft's category, with probability,
# combinatorics and random picks under Cards & Random.
CARDS = set("RAND RANDBETWEEN RANDARRAY CHOOSE CHOOSECOLS CHOOSEROWS COMBIN COMBINA PERMUT PERMUTATIONA FACT FACTDOUBLE MULTINOMIAL PROB STANDARDIZE PHI GAUSS FISHER FISHERINV".split())
def is_prob(n):
    return bool(re.search(r"\.(DIST|INV|TEST)|DIST$|^(CONFIDENCE|Z\.TEST|T\.|F\.|CHISQ|BINOM|NEGBINOM|HYPGEOM|POISSON|EXPON|GAMMA|BETA|LOGNORM|WEIBULL|NORM)", n))
CAT_SKILL = {
    "Statistical": "data", "Database": "data", "Cube": "data",
    "Lookup and reference": "map", "Web": "map",
    "Text": "text",
    "Logical": "games", "Information": "games",
    "Math and trigonometry": "math", "Engineering": "math",
    "Date and time": "time", "Financial": "time",
}
# Titan's three skills.
LAMBDA = set("LAMBDA LET MAP REDUCE SCAN BYROW BYCOL MAKEARRAY ISOMITTED".split())
SINGLE = set("""FILTER SORT SORTBY UNIQUE SEQUENCE RANDARRAY TEXTSPLIT TEXTBEFORE TEXTAFTER VSTACK HSTACK TOCOL TOROW
    WRAPROWS WRAPCOLS TAKE DROP EXPAND CHOOSECOLS CHOOSEROWS GROUPBY PIVOTBY TRIMRANGE XLOOKUP XMATCH ARRAYTOTEXT
    VALUETOTEXT REGEXTEST REGEXEXTRACT REGEXREPLACE PERCENTOF IMAGE MMULT MINVERSE MUNIT TRANSPOSE FREQUENCY LINEST
    LOGEST TREND GROWTH STOCKHISTORY""".split())
assert (LAMBDA | SINGLE) <= names, (LAMBDA | SINGLE) - names

out = []
for f in F:
    n = f["name"]
    skill = "cards" if (n in CARDS or (f["cat"] == "Statistical" and is_prob(n))) else CAT_SKILL[f["cat"]]
    titan = "lambda" if n in LAMBDA else "single" if n in SINGLE else "speed"
    out.append({**f, "skill": skill, "titan": titan, "tier": tier.get(n, 0), "extra": n in EXTRA})
json.dump(out, open("classified.json", "w"), indent=1)
import collections
print(len(out))
print("tiers", sorted(collections.Counter(o["tier"] for o in out).items()))
print("default-set tiers", sorted(collections.Counter(o["tier"] for o in out if not o["extra"]).items()))
print("skills", collections.Counter(o["skill"] for o in out))
print("titan", collections.Counter(o["titan"] for o in out))
print("skill x tier", {s: sorted(collections.Counter(o["tier"] for o in out if o["skill"] == s).items()) for s in CAT_SKILL.values()})
